package main

import (
	"log"
	"os"
	"path/filepath"
	"strings"
)

func generateStandardDLLTemplate() {
	var (
		buf strings.Builder
		err error
	)

	// main_dll_generated.go is only produced by the adaptive hijack path;
	// remove it so it doesn't conflict with a standard build.
	_ = os.Remove(filepath.Join("dll", "main_dll_generated.go"))

	buf.WriteString("//go:build windows\n\n")
	buf.WriteString("// Code generated by Johnny Dllaze; DO NOT EDIT.\n")
	buf.WriteString("package main\n\n")

	if err = writeCgoImport(&buf); err != nil {
		log.Fatal("[!] Failed to write CGO import: " + err.Error())
	}
	if err = writeDllInit(&buf, flags.exportFunc); err != nil {
		log.Fatal("[!] Failed to write DLL init: " + err.Error())
	}
	if err = writeDllExportFuncs(
		&buf, flags.exportFunc, flags.regSvr32,
	); err != nil {
		log.Fatal("[!] Failed to write DLL export funcs: " + err.Error())
	}

	err = os.WriteFile(
		filepath.Join("dll", "main_dll_entries_generated.go"),
		[]byte(buf.String()),
		0o600,
	)
	if err != nil {
		log.Fatal("[!] Failed to write DLL entries file: " + err.Error())
	}
}
