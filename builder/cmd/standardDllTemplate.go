package main

import (
	"fmt"
	"log"
	"os"
	"path/filepath"
)

func generateStandardDLLTemplate() {
	var (
		err error
		f   *os.File
	)

	// main_dll_generated.go is only produced by the adaptive hijack path;
	// remove it so it doesn't conflict with a standard build.
	_ = os.Remove(filepath.Join("dll", "main_dll_generated.go"))

	f, err = os.Create(filepath.Join("dll", "main_dll_entries_generated.go"))
	if err != nil {
		log.Fatal("[!] Failed to create DLL entries file: " + err.Error())
	}
	defer f.Close()

	fmt.Fprint(f, "//go:build windows\n\n")
	fmt.Fprint(f, "// Code generated by Johnny Dllaze; DO NOT EDIT.\n")
	fmt.Fprint(f, "package main\n\n")
	fmt.Fprint(f, "import \"C\"\n\n")

	if err = writeDllInit(f); err != nil {
		log.Fatal("[!] Failed to write DLL init: " + err.Error())
	}

	if flags.regSvr32 {
		if err = writeExportToSB(f, "DllRegisterServer"); err != nil {
			log.Fatal("[!] Failed to write DllRegisterServer: " + err.Error())
		}
		if err = writeExportToSB(f, "DllUnregisterServer"); err != nil {
			log.Fatal("[!] Failed to write DllUnregisterServer: " + err.Error())
		}
	}

	if flags.runDll32Func != "" {
		if err = writeExportToSB(f, flags.runDll32Func); err != nil {
			log.Fatal(
				"[!] Failed to write "+flags.runDll32Func+": "+err.Error(),
			)
		}
	}
}

