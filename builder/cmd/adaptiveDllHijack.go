package main

import (
	"fmt"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/mjwhitta/cplib"
)

func generateAdaptiveDLLTemplate() {
	var (
		buf       strings.Builder
		err       error
		exports   []string
		funcIndex int
	)

	exports, err = getDllExports(flags.adaptHijackDll)

	if err != nil {
		log.Fatal("[!] Failed to get DLL exports: " + err.Error())
	}

	if flags.exportFunc != "" {
		funcIndex = slices.Index(exports, flags.exportFunc)
		if funcIndex == -1 {
			log.Fatalf(
				"[!] Function %s not found in DLL exports",
				flags.exportFunc,
			)
		}
		exports = slices.Delete(exports, funcIndex, funcIndex+1)
	}

	if flags.regSvr32 {
		funcIndex = slices.Index(exports, "DllRegisterServer")
		if funcIndex != -1 {
			exports = slices.Delete(exports, funcIndex, funcIndex+1)
		}
		funcIndex = slices.Index(exports, "DllUnregisterServer")
		if funcIndex != -1 {
			exports = slices.Delete(exports, funcIndex, funcIndex+1)
		}
	}

	// Source: https://github.com/mjwhitta/cplib/blob/main/cplib.go
	err = cplib.GenerateGo(
		flags.adaptHijackDll,
		filepath.Join("dll", "main_dll_generated.go"),
		"windows",
		exports,
		nil,
		false,
	)
	if err != nil {
		log.Fatal("[!] Failed to generate Go code for DLL: " + err.Error())
	}

	buf.WriteString("//go:build windows\n\n")
	buf.WriteString("// Code generated by Johnny Dllaze; DO NOT EDIT.\n")
	buf.WriteString("package main\n\n")

	err = writeCgoImport(&buf)
	if err != nil {
		log.Fatal("[!] Failed to generate Go code for DLL: " + err.Error())
	}
	err = writeDllInit(&buf, flags.exportFunc)
	if err != nil {
		log.Fatal("[!] Failed to generate Go code for DLL: " + err.Error())
	}
	err = writeDllExportFuncs(&buf, flags.exportFunc, flags.regSvr32)
	if err != nil {
		log.Fatal("[!] Failed to generate Go code for DLL: " + err.Error())
	}

	err = os.WriteFile(
		filepath.Join("dll", "main_dll_entries_generated.go"),
		[]byte(buf.String()),
		0o600,
	)
	if err != nil {
		log.Fatal("[!] Failed to write DLL entries file: " + err.Error())
	}
}

func getDllExports(dllPath string) ([]string, error) {
	var (
		err     error
		exports []string
	)

	exports, err = cplib.PEExports(dllPath)
	if err != nil {
		return nil, fmt.Errorf("failed to parse DLL exports: %w", err)
	}

	return exports, nil
}

